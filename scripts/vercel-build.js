// Vercel build step for the static frontend.
//
// The frontend and the downloader API are deployed separately when the UI is
// hosted on Vercel (yt-dlp/ffmpeg cannot run in Vercel Functions). Set the
// GAC_API_BASE environment variable in the Vercel project to the deployed
// backend origin and this script writes it into public/config.js.
//
// If GAC_API_BASE is not set, the committed public/config.js is left untouched
// (so a manually configured URL keeps working).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const configPath = path.join(root, "public", "config.js");
const apiBase = String(process.env.GAC_API_BASE || "")
  .trim()
  .replace(/\/+$/, "");

if (!apiBase) {
  console.warn(
    "[vercel-build] GAC_API_BASE is not set; keeping the committed public/config.js. " +
      "The app will only work if that file points at a backend or the API is same-origin."
  );
  process.exit(0);
}

const body = `// Generated by scripts/vercel-build.js during the Vercel build.
// Set GAC_API_BASE in the Vercel project settings instead of editing this file.
window.GAC_API_BASE = ${JSON.stringify(apiBase)};
`;

fs.writeFileSync(configPath, body, "utf8");
console.log(`[vercel-build] public/config.js -> ${apiBase}`);
